package main

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"time"
)

const header = `# Release ledger shown on /work/. Generated by tools/ledger; do not edit it by hand.
# Track a KEP in ledger/keps.yaml, add PRs, posts, talks and exclusions in
# ledger/overrides.yaml, then run ` + "`make ledger`" + `.
#
# - stages and releases: kep.yaml ` + "`milestone`" + `, up to kep.yaml ` + "`stage`" + `, in
#   kubernetes/enhancements; a stage counts once its release is out (a v1.N.0 tag in
#   kubernetes/kubernetes);
# - first and last: the oldest and newest released stage; the page's release axis ends
#   at last, so the file changes only when the work does;
# - targets (` + "`target: true`" + `): a GA stage in the release in development, drawn only
#   while the KEP issue's milestone is that release and it carries lead-opted-in;
#   kep.yaml alone is not enough, it keeps a target after the release drops the KEP;
# - inDevelopment and checked: written only with a target; checked is the UTC date of the
#   run, and the site stops drawing targets 35 days after it, so an unmerged update
#   shows released stages only, never a stale target;
# - coauthors: kep.yaml ` + "`authors`" + `, without @aramase;
# - prs, posts, talks: ledger/overrides.yaml.
`

// noteWidth is the text width of a wrapped comment line, after the "# ".
const noteWidth = 76

// render writes the ledger as YAML in a fixed, reviewable layout: one key per line,
// short lists inline, longer string lists as blocks.
func render(l ledger) []byte {
	var b strings.Builder
	w := func(indent int, format string, args ...any) {
		b.WriteString(strings.Repeat(" ", indent))
		fmt.Fprintf(&b, format, args...)
		b.WriteByte('\n')
	}

	b.WriteString(header)
	b.WriteByte('\n')
	w(0, "kubernetes:")
	w(2, "first: %d   # v1.%d, the first release with a stage on the ledger", l.First, l.First)
	w(2, "last: %d    # v1.%d, the newest released stage on the ledger", l.Last, l.Last)
	if l.InDevelopment > 0 {
		w(2, "inDevelopment: %d   # v1.%d, in development: a target is drawn", l.InDevelopment, l.InDevelopment)
		w(2, "checked: %s   # the target was confirmed on this date", l.Checked.Format(time.DateOnly))
	}
	w(2, "features:")
	for i, f := range l.Features {
		if i > 0 {
			b.WriteByte('\n')
		}
		writeHead(w, 4, f)
		w(6, "stages:")
		for _, s := range f.Stages {
			w(8, "- stage: %s", s.Stage)
			w(10, "release: %d", s.Release)
			if s.Target {
				w(10, "target: true")
			}
			writeAnnotation(w, 10, s.annotation)
		}
		writeNotes(w, 8, f.Notes)
	}

	if len(l.Subprojects) > 0 {
		b.WriteByte('\n')
		w(0, "# Out-of-tree projects with a KEP, shown at the latest stage kep.yaml records.")
		w(0, "subprojects:")
		for i, p := range l.Subprojects {
			if i > 0 {
				b.WriteByte('\n')
			}
			s := p.Stages[0]
			writeHead(w, 2, p)
			w(4, "stage: %s", s.Stage)
			w(4, "release: %d", s.Release)
			writeList(w, 4, "talks", s.Talks)
			writeNotes(w, 4, p.Notes)
		}
	}
	return []byte(b.String())
}

type writer func(indent int, format string, args ...any)

func writeHead(w writer, indent int, e entry) {
	w(indent, "- id: %s", e.ID)
	w(indent+2, "name: %s", scalar(e.Name))
	w(indent+2, "kep: %d", e.KEP)
	w(indent+2, "path: %s", scalar(e.Path))
	w(indent+2, "sig: %s", scalar(e.SIG))
	w(indent+2, "coauthors: %s", inline(e.Coauthors))
}

func writeAnnotation(w writer, indent int, a annotation) {
	if len(a.PRs) > 0 {
		nums := make([]string, len(a.PRs))
		for i, n := range a.PRs {
			nums[i] = strconv.Itoa(n)
		}
		w(indent, "prs: [%s]", strings.Join(nums, ", "))
	}
	writeList(w, indent, "posts", a.Posts)
	writeList(w, indent, "talks", a.Talks)
}

// writeList writes one string inline and more as a block list.
func writeList(w writer, indent int, key string, items []string) {
	switch len(items) {
	case 0:
	case 1:
		w(indent, "%s: %s", key, inline(items))
	default:
		w(indent, "%s:", key)
		for _, s := range items {
			w(indent+2, "- %s", strconv.Quote(s))
		}
	}
}

func writeNotes(w writer, indent int, notes []string) {
	for _, n := range notes {
		for _, line := range wrap(n, noteWidth) {
			w(indent, "# %s", line)
		}
	}
}

func inline(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = strconv.Quote(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

var plainRE = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9 ./()_-]*$`)

// scalar leaves plain text unquoted and quotes anything YAML could read differently.
func scalar(s string) string {
	switch strings.ToLower(s) {
	case "true", "false", "yes", "no", "on", "off", "null", "y", "n":
		return strconv.Quote(s)
	}
	if plainRE.MatchString(s) && !strings.HasSuffix(s, " ") {
		return s
	}
	return strconv.Quote(s)
}

func wrap(s string, width int) []string {
	var lines []string
	line := ""
	for _, word := range strings.Fields(s) {
		switch {
		case line == "":
			line = word
		case len(line)+1+len(word) <= width:
			line += " " + word
		default:
			lines = append(lines, line)
			line = word
		}
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}
